#!/bin/bash
# type_text.sh — имитация печати переданного текста
# Использование: ./type_text.sh 'Ваш текст для ввода'

# Проверяем, передан ли аргумент (текст)
if [ -z "$1" ]; then
    echo "Использование: $0 'Ваш текст для ввода'"
    exit 1
fi

# Задержка в 5 секунд, чтобы вы успели переключить окно на нужное поле ввода
sleep 5

# Эмуляция ввода переданного текста
xdotool type --delay 100 "$1"
