#!/bin/bash
# задача_в_буфер.sh — кладёт в буфер обмена фразу (с пробелом в начале).
# Без аргумента: " задача: с помощью зрения найди координаты нижней кнопки копировать (два квадратика)"
# С аргументом: передаёт в буфер свою задачу.
# Использование: ./задача_в_буфер.sh   или   ./задача_в_буфер.sh "своя задача"

if [ -z "$1" ]; then
    TEXT=" задача: с помощью зрения найди координаты нижней кнопки копировать (два квадратика), подставь эти координаты в click_xy.py и выполни, после отработки click_xy.py выполни скрипт ku_ku.sh, затем прочитай буфер, это ответ от ИИ-дипсик"
else
    TEXT=" $1"
fi

printf '%s' "$TEXT" | xclip -selection clipboard
echo "Фраза в буфере: $TEXT"
